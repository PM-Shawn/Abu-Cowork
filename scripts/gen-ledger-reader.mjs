/**
 * Builds the CommonJS bundle the Electron main process uses to read a
 * conversation ledger, from the same TypeScript the renderer and the sidecar
 * run: src/core/session/ledgerReader.ts → electron/generated/ledgerReader.cjs.
 *
 * The bundle is tracked in git because the main process has no build step of
 * its own. `--check` rebuilds in memory and fails when the tracked file
 * differs, so an edit to the TypeScript cannot ship without its bundle.
 *
 * The output must be byte-identical on every machine, so every option below is
 * a constant and the build reads nothing but the entry point's import graph.
 * esbuild's own version is pinned by package-lock.json.
 *
 * Run it with `node` (the npm scripts do). The file carries no hashbang line:
 * `electron/ledgerReader.contract.test.ts` imports it, and Vite's SSR transform
 * only removes a hashbang that ends in a bare `\n`, which a CRLF checkout does
 * not have.
 */
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'src/core/session/ledgerReader.ts');
const OUT = path.join(ROOT, 'electron/generated/ledgerReader.cjs');
const BANNER = [
  '// GENERATED by scripts/gen-ledger-reader.mjs from src/core/session/ledgerReader.ts.',
  '// Do not edit. Regenerate with: npm run gen:ledger-reader',
  '',
].join('\n');

async function render() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'cjs',
    // The bundle's only requirer is `electron/catalogDb.cjs`, which the
    // Electron main process loads, so the syntax floor is Electron's own Node
    // major: Electron 43 (package.json) runs Node 24.
    target: 'node24',
    charset: 'utf8',
    legalComments: 'none',
    // Mirrors the `@` alias every other build in this repo sets.
    alias: { '@': path.join(ROOT, 'src') },
    // esbuild writes the entry point's path into the output as a relative
    // comment, so the working directory must not leak into the bundle.
    absWorkingDir: ROOT,
    banner: { js: BANNER },
  });
  return result.outputFiles[0].text;
}

/**
 * Is the tracked bundle the build of the current TypeScript?
 *
 * The comparison normalises the tracked text's line endings because the
 * working-tree form of a text file follows the machine's git configuration:
 * with `core.autocrlf=true` (the Git for Windows default, and what the
 * `windows-latest` CI runner uses) the checkout hands back `\r\n` while esbuild
 * always emits `\n`. What is tracked is LF either way — `.gitattributes` pins
 * it — so a CRLF working copy is the same bundle, not a stale one.
 */
export function isBundleCurrent(trackedText, freshText) {
  return trackedText.replace(/\r\n/g, '\n') === freshText;
}

/**
 * Running as a script? Only then does it build, compare and exit. Node gives
 * the module its real path while `argv[1]` keeps the path as it was typed, so
 * both sides are resolved through symlinks before they are compared.
 */
const invokedDirectly = Boolean(process.argv[1])
  && fs.realpathSync(path.resolve(process.argv[1])) === fs.realpathSync(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  const fresh = await render();
  if (process.argv.includes('--check')) {
    const tracked = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (tracked === null || !isBundleCurrent(tracked, fresh)) {
      console.error('electron/generated/ledgerReader.cjs is out of date. Run: npm run gen:ledger-reader');
      process.exit(1);
    }
    console.log('electron/generated/ledgerReader.cjs is up to date.');
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, fresh);
    console.log(`wrote ${path.relative(ROOT, OUT)}`);
  }
}
