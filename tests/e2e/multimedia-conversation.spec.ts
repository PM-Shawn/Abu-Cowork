test('image editing preserves layers, uses the bottom toolbar and keeps one ratio line', async () => {
  test.setTimeout(180_000);
  const root = createElectronDataRoot();
  const workspace = path.join(root.rootDir, 'workspace');
  fs.mkdirSync(workspace);
  const filePath = path.join(workspace, 'coffee.png');
  const secondPath = path.join(workspace, 'coffee-overhead.png');
  await sharp({ create: { width: 800, height: 600, channels: 3, background: '#dbc6a0' } }).png().toFile(filePath);
  await sharp({ create: { width: 600, height: 800, channels: 3, background: '#c6dba0' } }).png().toFile(secondPath);
  const model = await startOpenAiMock([
    { kind: 'tool-call', toolCallId: 'present-media', toolName: 'present_files', arguments: { files: [{ path: filePath }, { path: secondPath }] } },
    { kind: 'complete', responseText: '商品图片已准备好。' },
  ]);
  const { app } = await launchAbuElectron(root);
  try {
    const page = await app.firstWindow();
    await waitForApp(page);
    await page.evaluate(({ workspace, version }) => {
      localStorage.setItem('abu-projects', JSON.stringify({ version, state: { projects: {
        'media-project': { id: 'media-project', name: '媒体检查', workspacePath: workspace, pinned: false, archived: false, createdAt: 1_800_000_000_000, updatedAt: 1_800_000_000_000, lastActiveAt: 1_800_000_000_000 },
      } } }));
    }, { workspace, version: persistedStoreVersion('abu-projects') });
    await dismissFirstRunOverlays(page);
    await configureLocalMockProvider(page, model.baseUrl, { supportsTools: true, permissionMode: 'standard' });
    await page.getByRole('button', { name: '媒体检查', exact: true }).locator('xpath=..').getByRole('button', { name: '新任务', exact: true }).click();
    const composer = page.getByPlaceholder(CHAT_PLACEHOLDER);
    await composer.fill('显示商品图片');
    await composer.press('Enter');
    await expect(page.getByText('商品图片已准备好。', { exact: true })).toBeVisible({ timeout: 60_000 });
    const card = page.locator('.group\\/card').filter({ has: page.getByRole('img', { name: 'coffee.png', exact: true }) }).first();
    await expect(card).toBeVisible();
    const bounds = await card.boundingBox();
    await card.hover();
    await card.getByRole('button', { name: '修改图片', exact: true }).click();
    const preview = page.locator('[role="tabpanel"]:not([hidden])');
    await expect(preview.getByRole('button', { name: '宽高比', exact: true })).toBeVisible();
    await expect(preview.getByTestId('image-preview')).toBeVisible();
    await expect.poll(() => preview.getByRole('button', { name: '宽高比', exact: true }).evaluate(element => {
      const toolbar = element.getBoundingClientRect();
      const area = element.closest('[data-testid="image-preview"]')!.getBoundingClientRect();
      return area.height > 0 && toolbar.y > area.y + area.height / 2;
    })).toBe(true);
    expect((await card.boundingBox())!.height).toBe(bounds!.height);
    await composer.fill('保留咖啡包装');
    const toolbar = await preview.getByRole('button', { name: '宽高比', exact: true }).boundingBox();
    await preview.getByRole('button', { name: '宽高比', exact: true }).click();
    const ratio = page.getByRole('menuitem', { name: '1:1', exact: true });
    const menu = await page.getByRole('menu').boundingBox();
    expect(menu!.y).toBeLessThan(toolbar!.y);
    await ratio.click();
    await expect(composer).toHaveValue('保留咖啡包装\n将宽高比设为 1:1');
    await expect(composer).toBeFocused();
    await preview.getByRole('button', { name: '宽高比', exact: true }).click();
    await page.getByRole('menuitem', { name: '16:9', exact: true }).click();
    await expect(composer).toHaveValue('保留咖啡包装\n将宽高比设为 16:9');
    await preview.getByRole('button', { name: '批注', exact: true }).click();
    const image = preview.getByRole('img', { name: 'coffee.png', exact: true });
    const rectangle = await image.boundingBox();
    await page.mouse.click(rectangle!.x + rectangle!.width / 2, rectangle!.y + rectangle!.height / 2);
    const commentEditor = page.getByTestId('image-comment-editor');
    const firstComment = page.getByRole('textbox', { name: '批注 1', exact: true });
    await expect(firstComment).toBeFocused();
    await firstComment.fill('保留包装文字');
    const firstMarker = preview.getByRole('button', { name: '批注 1', exact: true });
    const markerBox = await firstMarker.boundingBox();
    const editorBox = await commentEditor.boundingBox();
    expect(Math.min(Math.abs(editorBox!.x - markerBox!.x - markerBox!.width), Math.abs(markerBox!.x - editorBox!.x - editorBox!.width))).toBeLessThan(12);
    expect(Math.abs(editorBox!.y - markerBox!.y)).toBeLessThan(30);
    await firstComment.press('Enter');
    await expect(commentEditor).toBeHidden();
    await expect(firstMarker).toBeFocused();
    await firstMarker.press('Enter');
    await expect(firstComment).toHaveValue('保留包装文字');
    await firstComment.press('Shift+Enter');
    await expect(firstComment).toHaveValue('保留包装文字\n');
    await firstComment.fill('保留包装文字');
    await firstComment.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
    await expect(firstComment).toBeVisible();
    await firstComment.press('Escape');
    await expect(commentEditor).toBeHidden();
    await preview.getByRole('button', { name: '向右旋转', exact: true }).click();
    await preview.getByRole('button', { name: '放大图片', exact: true }).click();
    const rotatedPoint = await image.evaluate(element => {
      const image = element as HTMLImageElement;
      const bounds = image.getBoundingClientRect();
      const vector = new DOMMatrix(getComputedStyle(image).transform).transformPoint({ x: -image.offsetWidth / 4, y: -image.offsetHeight / 4, w: 0 });
      return { x: bounds.x + bounds.width / 2 + vector.x, y: bounds.y + bounds.height / 2 + vector.y };
    });
    await page.mouse.click(rotatedPoint.x, rotatedPoint.y);
    await expect(page.getByRole('textbox', { name: '批注 2', exact: true })).toBeFocused();
    await expect(commentEditor.getByRole('textbox')).toHaveCount(1);
    await page.getByRole('textbox', { name: '批注 2', exact: true }).fill('修改背景');
    const secondMarker = preview.getByRole('button', { name: '批注 2', exact: true });
    const annotation = await secondMarker.boundingBox();
    expect(annotation!.x + annotation!.width / 2).toBeCloseTo(rotatedPoint.x, 0);
    expect(annotation!.y + annotation!.height / 2).toBeCloseTo(rotatedPoint.y, 0);
    await firstMarker.click();
    await expect(firstComment).toBeFocused();
    await expect(firstComment).toHaveValue('保留包装文字');
    await expect(commentEditor.getByRole('textbox')).toHaveCount(1);
    await secondMarker.click();
    await expect(page.getByRole('textbox', { name: '批注 2', exact: true })).toHaveValue('修改背景');
    await commentEditor.getByRole('button', { name: '删除', exact: true }).click();
    await expect(secondMarker).toHaveCount(0);
    await expect(commentEditor).toBeHidden();
    await preview.getByRole('button', { name: '重置视图', exact: true }).click();
    const edgeImage = await image.boundingBox();
    await page.mouse.click(edgeImage!.x + edgeImage!.width - 5, edgeImage!.y + edgeImage!.height - 5);
    const edgeComment = page.getByRole('textbox', { name: '批注 2', exact: true });
    await expect(edgeComment).toBeFocused();
    await edgeComment.fill('背景保持一致');
    const edgeEditor = await commentEditor.boundingBox();
    const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }));
    expect(edgeEditor!.x).toBeGreaterThanOrEqual(8);
    expect(edgeEditor!.y).toBeGreaterThanOrEqual(8);
    expect(edgeEditor!.x + edgeEditor!.width).toBeLessThanOrEqual(viewport.width - 8);
    expect(edgeEditor!.y + edgeEditor!.height).toBeLessThanOrEqual(viewport.height - 8);
    await commentEditor.getByRole('button', { name: '保存', exact: true }).click();
    await expect(commentEditor).toBeHidden();
    await preview.getByRole('button', { name: '选择区域', exact: true }).click();
    const regionBounds = await image.boundingBox();
    await page.mouse.move(regionBounds!.x + regionBounds!.width * 0.2, regionBounds!.y + regionBounds!.height * 0.2);
    await page.mouse.down();
    await page.mouse.move(regionBounds!.x + regionBounds!.width * 0.35, regionBounds!.y + regionBounds!.height * 0.35, { steps: 8 });
    await page.mouse.up();
    await expect(preview.getByRole('button', { name: '撤销', exact: true })).toBeEnabled();
    await preview.getByRole('button', { name: '撤销', exact: true }).click();
    await expect(preview.getByRole('button', { name: '重做', exact: true })).toBeEnabled();
    await preview.getByRole('button', { name: '重做', exact: true }).click();
    await preview.getByRole('button', { name: '批注', exact: true }).click();
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留包装文字');
    await preview.getByRole('button', { name: 'coffee-overhead.png', exact: true }).click();
    await expect(commentEditor).toBeHidden();
    await preview.getByRole('button', { name: '批注', exact: true }).click();
    await expect(preview.getByRole('button', { name: '批注', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const overhead = preview.getByRole('img', { name: 'coffee-overhead.png', exact: true });
    await expect(overhead.locator('..')).toHaveClass(/cursor-crosshair/);
    await expect.poll(() => overhead.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(600);
    await overhead.click({ position: { x: 35, y: 35 } });
    await expect(firstComment).toBeFocused();
    await firstComment.fill('保留俯视构图');
    await firstComment.press('Enter');
    await composer.fill('俯视图的修改要求');
    await preview.getByRole('button', { name: 'coffee.png', exact: true }).click();
    await expect(firstMarker).toBeVisible();
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留包装文字');
    await expect(composer).toHaveValue('保留咖啡包装\n将宽高比设为 16:9');
    await firstComment.press('Escape');
    await preview.getByRole('button', { name: 'coffee-overhead.png', exact: true }).click();
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留俯视构图');
    await expect(composer).toHaveValue('俯视图的修改要求');
    await firstComment.press('Escape');
    await preview.getByRole('button', { name: 'coffee.png', exact: true }).click();
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留包装文字');
    const newPoint = await image.evaluate(element => {
      const bounds = element.getBoundingClientRect();
      return { x: bounds.x + bounds.width * 0.12, y: bounds.y + bounds.height * 0.12 };
    });
    await page.mouse.click(newPoint.x, newPoint.y);
    const thirdComment = page.getByRole('textbox', { name: '批注 3', exact: true });
    await expect(thirdComment).toBeFocused();
    await expect(commentEditor.getByRole('textbox')).toHaveCount(1);
    await thirdComment.press('Escape');
    const thirdMarker = preview.getByRole('button', { name: '批注 3', exact: true });
    await thirdMarker.click();
    await expect(thirdComment).toHaveValue('');
    await thirdComment.press('Tab');
    const deleteComment = commentEditor.getByRole('button', { name: '删除', exact: true });
    await expect(deleteComment).toBeFocused();
    await deleteComment.press('Enter');
    await expect(thirdMarker).toHaveCount(0);
    await expect(image.locator('..')).toBeFocused();
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留包装文字');
    fs.writeFileSync(filePath, await sharp({ create: { width: 200, height: 100, channels: 3, background: '#ffffff' } }).png().toBuffer());
    await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(800);
    await firstComment.press('Escape');
    await composer.press('Enter');
    await expect(page.getByText('请在设置的 AI 服务中配置支持图片编辑的服务，当前修改要求已保留。', { exact: true })).toBeVisible();
    await expect(composer).toHaveValue('保留咖啡包装\n将宽高比设为 16:9');
    await firstMarker.click();
    await expect(firstComment).toHaveValue('保留包装文字');
    await firstComment.press('Escape');
    await preview.getByRole('button', { name: '全屏', exact: true }).click();
    await firstMarker.click();
    await expect(firstComment).toBeFocused();
    await firstComment.press('Escape');
    await expect(commentEditor).toBeHidden();
    await expect(preview.getByRole('button', { name: '退出全屏', exact: true })).toBeVisible();
    await firstMarker.press('Enter');
    await expect(firstComment).toBeFocused();
    await firstComment.press('Escape');
    await preview.getByRole('button', { name: '退出全屏', exact: true }).click();
  } finally {
    await closeAbuElectron(app);
    await model.close();
    removeElectronDataRoot(root);
  }
});

for (const format of ['mp4', 'webm']) test(`${format} native video controls play, seek, preserve fullscreen progress and pause the previous video`, async () => {
  test.setTimeout(180_000);
  const root = createElectronDataRoot();
  const workspace = path.join(root.rootDir, 'workspace');
  fs.mkdirSync(workspace);
  const firstPath = path.join(workspace, `product-one.${format}`);
  const secondPath = path.join(workspace, `product-two.${format}`);
  const invalidPath = path.join(workspace, 'unplayable.mp4');
  fs.writeFileSync(invalidPath, 'This file contains no video stream.');
  fs.copyFileSync(path.resolve(`tests/e2e/fixtures/media/playback.${format}`), firstPath);
  fs.copyFileSync(firstPath, secondPath);
  const model = await startOpenAiMock([
    { kind: 'tool-call', toolCallId: 'present-videos', toolName: 'present_files', arguments: { files: [{ path: firstPath }, { path: secondPath }, { path: invalidPath }] } },
    { kind: 'complete', responseText: '视频已准备好。' },
  ]);
  const { app } = await launchAbuElectron(root);
  try {
    const page = await app.firstWindow();
    await waitForApp(page);
    await page.evaluate(({ workspace, version }) => {
      localStorage.setItem('abu-projects', JSON.stringify({ version, state: { projects: {
        'video-project': { id: 'video-project', name: '视频检查', workspacePath: workspace, pinned: false, archived: false, createdAt: 1_800_000_000_000, updatedAt: 1_800_000_000_000, lastActiveAt: 1_800_000_000_000 },
      } } }));
    }, { workspace, version: persistedStoreVersion('abu-projects') });
    await dismissFirstRunOverlays(page);
    await configureLocalMockProvider(page, model.baseUrl, { supportsTools: true, permissionMode: 'standard' });
    await page.getByRole('button', { name: '视频检查', exact: true }).locator('xpath=..').getByRole('button', { name: '新任务', exact: true }).click();
    const composer = page.getByPlaceholder(CHAT_PLACEHOLDER);
    await composer.fill('显示商品视频');
    await composer.press('Enter');
    await expect(page.getByText('视频已准备好。', { exact: true })).toBeVisible({ timeout: 60_000 });
    const first = page.locator(`video[aria-label="product-one.${format}"]`).first();
    const second = page.locator(`video[aria-label="product-two.${format}"]`).first();
    await expect(page.getByTestId('chat-message-list').getByText('当前播放器不支持这个视频格式，可以用本地应用打开。', { exact: true })).toBeVisible();
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).duration)).toBeCloseTo(8, 1);
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2);
    await composer.hover();
    await expect(first).not.toHaveAttribute('controls', '');
    await first.hover();
    await expect(first).toHaveAttribute('controls', '');
    await composer.hover();
    await expect(first).not.toHaveAttribute('controls', '');
    await first.focus();
    await expect(first).toHaveAttribute('controls', '');
    await composer.focus();
    await expect(first).not.toHaveAttribute('controls', '');
    await first.press('Space');
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).paused)).toBe(false);
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).currentTime)).toBeGreaterThan(0);
    await first.press('Space');
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).paused)).toBe(true);
    await first.evaluate(video => { (video as HTMLVideoElement).currentTime = 4; });
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).seeking)).toBe(false);
    await first.hover();
    await first.locator('..').getByRole('button', { name: '全屏', exact: true }).click();
    await expect.poll(() => page.evaluate(() => document.fullscreenElement?.tagName)).toBe('VIDEO');
    await page.keyboard.press('Escape');
    await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true);
    for (let cycle = 0; cycle < 2; cycle += 1) {
      const fullscreen = first.locator('..').getByRole('button', { name: '全屏', exact: true });
      await expect(fullscreen).toBeFocused();
      await fullscreen.click();
      await expect.poll(() => page.evaluate(() => document.fullscreenElement?.tagName)).toBe('VIDEO');
      await page.keyboard.press('Escape');
      await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true);
    }
    expect(await first.evaluate(video => (video as HTMLVideoElement).currentTime)).toBeCloseTo(4, 1);
    await first.press('Space');
    await second.press('Space');
    await expect.poll(() => second.evaluate(video => (video as HTMLVideoElement).paused)).toBe(false);
    await expect.poll(() => first.evaluate(video => (video as HTMLVideoElement).paused)).toBe(true);
    await composer.fill('保留');
    await composer.press('Space');
    await expect(composer).toHaveValue('保留 ');
    await page.getByRole('button', { name: '显示侧栏', exact: true }).click();
    await page.getByLabel('Main navigation').getByRole('button', { name: '新任务', exact: true }).click();
    await expect.poll(() => page.locator('video').evaluateAll(videos => videos.every(video => video.paused))).toBe(true);
  } finally {
    await closeAbuElectron(app);
    await model.close();
    removeElectronDataRoot(root);
  }
});
