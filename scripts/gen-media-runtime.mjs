import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'electron/generated/mediaRuntime.cjs');
const result = await build({
  entryPoints: [path.join(root, 'src/core/media/hostModel.ts')], bundle: true, write: false,
  platform: 'node', format: 'cjs', target: 'node24', charset: 'utf8', legalComments: 'none', jsx: 'automatic',
  alias: { '@': path.join(root, 'src') }, absWorkingDir: root,
  banner: { js: '// GENERATED by scripts/gen-media-runtime.mjs. Regenerate with npm run build:media-runtime.' },
});
const fresh = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== fresh) {
    throw new Error('Media runtime is out of date. Run npm run build:media-runtime.');
  }
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, fresh);
}
