#!/usr/bin/env node
/**
 * Test inventory — counts test files per layer by filename convention and
 * keeps the generated block in TESTING.md in sync.
 *
 *   node scripts/test-inventory.mjs --write   # rewrite the block
 *   node scripts/test-inventory.mjs --check   # exit 1 if the block is stale
 *
 * WHY: hand-written counts in docs rot ("2400+ tests", "45 files") and AI
 * agents read docs as ground truth. Numbers must come from the tree.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const START = '<!-- test-inventory:start -->';
export const END = '<!-- test-inventory:end -->';

const IGNORED_DIRS = new Set(['node_modules', 'dist', 'dist-electron-spike', 'coverage', 'test-results', '.git', 'target', 'src-tauri', '.next', '.vitest-reports']);

function walk(dir, out = []) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (IGNORED_DIRS.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

export function collectInventory(repoRoot) {
  const files = walk(repoRoot).map((f) => path.relative(repoRoot, f).split(path.sep).join('/'));
  const inv = { unit: 0, integration: 0, contract: 0, quarantine: 0, e2eWeb: 0, e2eElectron: 0, nodeTest: 0 };
  for (const f of files) {
    if (/^e2e\/.*\.spec\.ts$/.test(f)) { inv.e2eWeb++; continue; }
    if (/^tests\/e2e\/.*\.spec\.ts$/.test(f)) { inv.e2eElectron++; continue; }
    if (/\.test\.(mjs|cjs)$/.test(f)) { inv.nodeTest++; continue; }
    if (!/\.test\.tsx?$/.test(f)) continue;
    if (f.startsWith('src/__tests__/quarantine/')) { inv.quarantine++; continue; }
    if (/\.integration\.test\.tsx?$/.test(f)) { inv.integration++; continue; }
    if (/\.contract\.test\.tsx?$/.test(f)) { inv.contract++; continue; }
    inv.unit++;
  }
  return inv;
}

export function renderBlock(inv) {
  return [
    START,
    '<!-- generated by `npm run test:inventory` — do not edit by hand; CI runs `test:inventory:check` -->',
    '| Layer | Files |',
    '|---|---|',
    `| Unit (\`*.test.ts(x)\`, Vitest) | ${inv.unit} |`,
    `| Integration (\`*.integration.test.ts\`) | ${inv.integration} |`,
    `| Contract (\`*.contract.test.ts\`) | ${inv.contract} |`,
    `| Quarantined (\`src/__tests__/quarantine/\`) | ${inv.quarantine} |`,
    `| Web E2E (\`e2e/*.spec.ts\`, Playwright) | ${inv.e2eWeb} |`,
    `| Real-Electron E2E (\`tests/e2e/*.spec.ts\`) | ${inv.e2eElectron} |`,
    `| Node \`node:test\` scripts (\`*.test.mjs\` / \`*.test.cjs\`) | ${inv.nodeTest} |`,
    END,
  ].join('\n');
}

export function applyBlock(markdown, block) {
  const s = markdown.indexOf(START);
  const e = markdown.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`test-inventory markers not found (${START} … ${END})`);
  return markdown.slice(0, s) + block + markdown.slice(e + END.length);
}

function main(argv) {
  const rootIdx = argv.indexOf('--root');
  const repoRoot = rootIdx !== -1 ? path.resolve(argv[rootIdx + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const docPath = path.join(repoRoot, 'TESTING.md');
  const current = readFileSync(docPath, 'utf8');
  const next = applyBlock(current, renderBlock(collectInventory(repoRoot)));
  if (argv.includes('--write')) {
    if (next !== current) writeFileSync(docPath, next);
    console.log('test-inventory: TESTING.md block written');
    return 0;
  }
  if (next === current) { console.log('test-inventory: TESTING.md block is up to date'); return 0; }
  console.error('test-inventory: TESTING.md block is STALE. Run `npm run test:inventory` and commit the result.');
  return 1;
}

const invokedDirectly = Boolean(process.argv[1]) && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  process.exit(main(process.argv.slice(2)));
}
