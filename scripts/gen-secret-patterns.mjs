import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'electron/generated/secretPatterns.cjs');
const result = await build({
  entryPoints: [path.join(root, 'src/utils/secretPatterns.ts')],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'cjs',
  target: 'node24',
  charset: 'utf8',
  legalComments: 'none',
  alias: { '@': path.join(root, 'src') },
  absWorkingDir: root,
  banner: { js: '// GENERATED by scripts/gen-secret-patterns.mjs. Run: npm run gen:secret-patterns\n' },
});
const fresh = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const tracked = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : null;
  if (tracked !== fresh) {
    console.error('electron/generated/secretPatterns.cjs is out of date. Run: npm run gen:secret-patterns');
    process.exit(1);
  }
  console.log('electron/generated/secretPatterns.cjs is up to date.');
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, fresh);
  console.log('wrote electron/generated/secretPatterns.cjs');
}
